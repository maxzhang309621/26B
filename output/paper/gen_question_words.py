        "交会角降至约 15° 时，$r$ 可超过 20 m，can_clear_20 为假，必须转入第三站或 creep。"
        "与 Jung 上界对照时恒有 $r\\le d/\\sqrt{3}<d/2$，说明最小包围圆判据更紧，直径圆用来回答赛题关于覆盖的设问。"
