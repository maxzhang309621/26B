def h1(d: PaperDoc, q: int):
    d.add_heading1(f"{_cn_num(CH[q])}、 问题{CN[q]}：{SUB[q]}")


def _cn_num(n: int) -> str:
    return {5: "五", 6: "六", 7: "七", 8: "八"}[n]


def h2(d: PaperDoc, q: int, k: int, title: str):
    d.add_heading2(f"{CH[q]}.{k}  {title}")


def h3(d: PaperDoc, q: int, k: int, m: int, title: str):
    d.add_heading3(f"{CH[q]}.{k}.{m}  {title}")


