        "其中，$\\mathbf{u}_+$、$\\mathbf{u}_-$ 分别对应误差上、下界方向；$\\theta$ 为该站示向度。点 $P$ 落在该站可接受角扇内，当且仅当向量 $P-S$ 夹在两条边界射线之间。",
